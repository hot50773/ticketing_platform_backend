    # ----------------------------------------------------------------------- #
    # Internals
    # ----------------------------------------------------------------------- #
    async def _apply(self, instance) -> None:
        """Flush a mutation and re-read the DB-generated columns."""
        self._session.add(instance)
        await self._session.flush()
        await self._session.refresh(instance)

